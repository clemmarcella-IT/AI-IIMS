<?php

use App\Enums\Role as RoleEnum;
use App\Jobs\WarmLessonAiFeedback;
use App\Models\Lesson;
use App\Models\LessonActivity;
use App\Models\LessonQuestion;
use App\Models\Teacher;
use App\Models\User;
use App\Services\GeminiService;
use Illuminate\Contracts\Cache\Lock;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Queue;
use Spatie\Permission\Models\Role;
use Spatie\Permission\PermissionRegistrar;

uses(RefreshDatabase::class);

beforeEach(function () {
    config([
        'cache.default' => 'array',
        'services.gemini.key' => 'test-key',
        'services.gemini.model' => 'gemini-test',
    ]);

    Cache::flush();
});

function fakeGeminiExplanation(string $explanation = 'Helpful explanation.'): void
{
    Http::fake([
        'generativelanguage.googleapis.com/*' => Http::response([
            'candidates' => [[
                'content' => ['parts' => [['text' => $explanation]]],
            ]],
        ]),
    ]);
}

function createAiFeedbackTeacher(): array
{
    app(PermissionRegistrar::class)->forgetCachedPermissions();
    Role::firstOrCreate(['name' => RoleEnum::TEACHER->value]);

    $user = User::factory()->create();
    $user->assignRole(RoleEnum::TEACHER->value);

    $teacher = Teacher::query()->create([
        'user_id' => $user->id,
        'employee_no' => 'AI-'.$user->id,
        'first_name' => 'Grace',
        'last_name' => 'Hopper',
    ]);

    return [$user, $teacher];
}

it('reuses normalized successful wrong-answer explanations', function () {
    fakeGeminiExplanation();
    $gemini = app(GeminiService::class);

    $first = $gemini->explainWrongAnswer(
        'Why do plants need light?',
        '  To stay   warm ',
        'To make food',
    );
    $second = $gemini->explainWrongAnswer(
        'Why do plants need light?',
        'To stay warm',
        'To make food',
    );

    expect($first)->toBe('Helpful explanation.')
        ->and($second)->toBe($first);
    Http::assertSentCount(1);
});

it('separates different wrong answers', function () {
    fakeGeminiExplanation();
    $gemini = app(GeminiService::class);

    $gemini->explainWrongAnswer('Question', 'Wrong A', 'Correct');
    $gemini->explainWrongAnswer('Question', 'Wrong B', 'Correct');

    Http::assertSentCount(2);
});

it('checks the cache again after acquiring the generation lock', function () {
    Http::fake();

    $lock = Mockery::mock(Lock::class);
    $lock->shouldReceive('block')
        ->once()
        ->with(400, Mockery::type('Closure'))
        ->andReturnUsing(fn (int $seconds, Closure $callback): string => $callback());

    Cache::shouldReceive('get')
        ->twice()
        ->andReturn(null, 'Explanation generated by the first request.');
    Cache::shouldReceive('lock')
        ->once()
        ->andReturn($lock);

    $result = app(GeminiService::class)
        ->explainWrongAnswer('Question', 'Wrong', 'Correct');

    expect($result)->toBe('Explanation generated by the first request.');
    Http::assertNothingSent();
});

it('does not cache failed Gemini feedback', function () {
    Http::fake([
        'generativelanguage.googleapis.com/*' => Http::response([], 500),
    ]);
    $gemini = app(GeminiService::class);

    $first = $gemini->explainWrongAnswer('Question', 'Wrong', 'Correct');
    $second = $gemini->explainWrongAnswer('Question', 'Wrong', 'Correct');

    expect($first)->toContain('currently unavailable')
        ->and($second)->toBe($first);
    Http::assertSentCount(6);
});

it('warms only predictable incorrect choices', function () {
    [, $teacher] = createAiFeedbackTeacher();
    fakeGeminiExplanation();

    $lesson = Lesson::query()->create([
        'teacher_id' => $teacher->id,
        'title' => 'Warm lesson',
        'difficulty_level' => 'beginner',
        'is_published' => true,
    ]);

    LessonQuestion::query()->create([
        'lesson_id' => $lesson->id,
        'question_text' => 'Pick B',
        'option_a' => 'A choice',
        'option_b' => 'B choice',
        'option_c' => 'C choice',
        'option_d' => 'D choice',
        'correct_answer' => 'B',
    ]);

    LessonActivity::query()->create([
        'lesson_id' => $lesson->id,
        'type' => 'mini_quiz',
        'title' => 'Pick blue',
        'payload' => ['question' => 'Pick blue', 'choices' => ['Red', 'Blue', 'Green']],
        'correct_answer' => 'Blue',
    ]);

    LessonActivity::query()->create([
        'lesson_id' => $lesson->id,
        'type' => 'true_false',
        'title' => 'The sky is blue',
        'payload' => ['statement' => 'The sky is blue'],
        'correct_answer' => true,
    ]);

    LessonActivity::query()->create([
        'lesson_id' => $lesson->id,
        'type' => 'fill_blank',
        'title' => 'Open answer',
        'payload' => ['sentence' => 'The sky is _____.'],
        'correct_answer' => 'blue',
    ]);

    (new WarmLessonAiFeedback($lesson->id))->handle(app(GeminiService::class));

    Http::assertSentCount(6);
});

it('queues warmup for published lessons but not drafts', function () {
    Queue::fake();
    [$user] = createAiFeedbackTeacher();

    $payload = [
        'title' => 'Queued lesson',
        'difficulty_level' => 'beginner',
        'sections' => [],
        'media' => [],
        'activities' => [],
    ];

    $this->actingAs($user)->post(route('teacher.lessons.store'), [
        ...$payload,
        'is_published' => false,
    ])->assertSessionHasNoErrors();

    Queue::assertNothingPushed();

    $this->actingAs($user)->post(route('teacher.lessons.store'), [
        ...$payload,
        'title' => 'Published lesson',
        'is_published' => true,
    ])->assertSessionHasNoErrors();

    Queue::assertPushed(WarmLessonAiFeedback::class, 1);
});

it('queues warmup for published question changes and batch republishing', function () {
    Queue::fake();
    [$user, $teacher] = createAiFeedbackTeacher();

    $lesson = Lesson::query()->create([
        'teacher_id' => $teacher->id,
        'title' => 'Published questions',
        'difficulty_level' => 'beginner',
        'is_published' => true,
    ]);

    $questionPayload = [
        'lesson_id' => $lesson->id,
        'question_text' => 'Pick B',
        'option_a' => 'A choice',
        'option_b' => 'B choice',
        'option_c' => 'C choice',
        'option_d' => 'D choice',
        'correct_answer' => 'B',
    ];

    $this->actingAs($user)
        ->post(route('teacher.questions.store'), $questionPayload)
        ->assertSessionHasNoErrors();

    $question = $lesson->questions()->firstOrFail();

    $this->actingAs($user)
        ->put(route('teacher.questions.update', $question), [
            ...$questionPayload,
            'question_text' => 'Still pick B',
        ])
        ->assertSessionHasNoErrors();

    $this->actingAs($user)
        ->post(route('teacher.lessons.batch-republish'), [
            'lesson_ids' => [$lesson->id],
        ])
        ->assertSessionHasNoErrors();

    Queue::assertPushed(WarmLessonAiFeedback::class, 3);
});

it('queues all existing published lessons from the warmup command', function () {
    Queue::fake();
    [, $teacher] = createAiFeedbackTeacher();

    Lesson::query()->create([
        'teacher_id' => $teacher->id,
        'title' => 'Published',
        'difficulty_level' => 'beginner',
        'is_published' => true,
    ]);
    Lesson::query()->create([
        'teacher_id' => $teacher->id,
        'title' => 'Draft',
        'difficulty_level' => 'beginner',
        'is_published' => false,
    ]);

    $this->artisan('ai-feedback:warm')
        ->expectsOutput('Queued AI feedback warmup for 1 published lessons.')
        ->assertSuccessful();

    Queue::assertPushed(WarmLessonAiFeedback::class, 1);
});
